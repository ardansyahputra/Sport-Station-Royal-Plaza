export function computeLowStockAlerts(products: Product[], threshold = 3): LowStockAlert[] {
  const alerts: LowStockAlert[] = [];
  products.forEach((product) => {
    product.sizes.forEach((size) => {
      if (size.stock <= threshold && size.stock >= 0) {
        alerts.push({
          id: `alert-${product.id}-eu${size.eu}`,
          productId: product.id,
          productCode: product.productCode,
          brand: product.brand,
          modelName: product.modelName,
          color: product.color,
          sizeEU: size.eu,
          stock: size.stock,
          dismissed: false,
        });
      }
    });
  });
  return alerts;
}

export function formatIDR(amount: number): string {
  return 'Rp. ' + amount.toLocaleString('id-ID').replace(/,/g, '.');
}

export function getTotalStock(products: Product[]): number {
  return products.reduce((sum, p) => sum + p.sizes.reduce((s, sz) => s + sz.stock, 0), 0);
}

export function getDiscountDistribution(products: Product[]): { discount: string; count: number }[] {
  const tiers = [0, 50, 70, 80] as const;
  return tiers.map((tier) => ({
    discount: `${tier}%`,
    count: products.filter((p) => p.discountPercent === tier).length,
  }));
}

export function getStockByBrand(products: Product[]): { brand: string; stock: number }[] {
  const brands = ['Airwalk', 'Converse', 'Diadora', 'New Balance', 'Reebok'] as const;
  return brands.map((brand) => ({
    brand,
    stock: products
      .filter((p) => p.brand === brand)
      .reduce((sum, p) => sum + p.sizes.reduce((s, sz) => s + sz.stock, 0), 0),
  }));
}